export interface CayleyCellDatum {
  row: number;
  col: number;
  rowLabel: string;
  colLabel: string;
  productIndex: number;
  productLabel: string;
  productOrder: number;
  commutes: boolean;
  reverseProductLabel: string;
}

export interface VisualCheatSheetData {
  group: FiniteGroup;
  cayleyCells: CayleyCellDatum[];
  lattice: SubgroupLatticeGraph;
  conjugacy: ConjugacyAnalysis;
  normalSubgroupCount: number;
  isCyclic: boolean;
  maxElementOrder: number;
  nonCommutingPairsCount: number;
}

export function buildVisualCheatSheetData(group: FiniteGroup): VisualCheatSheetData {
  const cayleyCells: CayleyCellDatum[] = [];
  let nonCommutingPairsCount = 0;

  for (let r = 0; r < group.order; r++) {
    for (let c = 0; c < group.order; c++) {
      const productIndex = group.table[r][c];
      const reverseIndex = group.table[c][r];
      const commutes = productIndex === reverseIndex;
      if (r < c && !commutes) {
        nonCommutingPairsCount++;
      }
      cayleyCells.push({
        row: r,
        col: c,
        rowLabel: group.elements[r],
        colLabel: group.elements[c],
        productIndex,
        productLabel: group.elements[productIndex],
        productOrder: group.orders[productIndex],
        commutes,
        reverseProductLabel: group.elements[reverseIndex],
      });
    }
  }

  const lattice = buildSubgroupLattice(group);
  const conjugacy = analyzeConjugacyClasses(group);
  const normalSubgroupCount = lattice.nodes.filter((n) => n.isNormal).length;
  const maxElementOrder = Math.max(...group.orders);
  const isCyclic = maxElementOrder === group.order;

  return {
    group,
    cayleyCells,
    lattice,
    conjugacy,
    normalSubgroupCount,
    isCyclic,
    maxElementOrder,
    nonCommutingPairsCount,
  };
}
